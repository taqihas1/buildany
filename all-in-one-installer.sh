# Proposal Knowledge Base Skill

Store, query, and maintain reusable proposal content.

## Quick Start

```bash
cd ~/.openclaw/skills/proposal-kb

# Generate draft intake
python3 scripts/query_kb.py \
  --kb assets/kb.json \
  --industry manufacturing \
  --project-type cloud_migration \
  --client "Acme Corp" \
  --output /tmp/draft.json

# Update KB with new case study
python3 scripts/update_kb.py \
  --kb assets/kb.json \
  --add-case-study new-project.json
```

## Maintenance Schedule

- After every win: Add case study
- After every loss: Log win/loss with lessons
- Quarterly: Review differentiators and rates
- Annually: Update vendor profile and certifications
