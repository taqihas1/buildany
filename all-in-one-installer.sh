#!/usr/bin/env python3
"""Query Knowledge Base and generate draft intake JSON."""
import json, argparse

def load_kb(path):
    with open(path, 'r') as f:
        return json.load(f)

def filter_case_studies(case_studies, industry=None):
    if not industry:
        return case_studies[:2] if case_studies else []
    filtered = [cs for cs in case_studies if cs.get('industry') == industry]
    return filtered if filtered else case_studies[:2]

def get_team_template(templates, project_type):
    return templates.get(project_type, templates.get('cloud_migration', {"roles": []}))

def get_differentiators(differentiators, industry):
    return differentiators.get(industry, differentiators.get('general', []))

def calculate_pricing(rates, team_template, duration_weeks=24):
    total = 0
    for role in team_template.get('roles', []):
        rate = rates.get(role['role'].lower().replace(' ', '_'), 1000)
        count = role.get('count', 1)
        allocation = role.get('allocation_percent', 100) / 100
        working_days = duration_weeks * 5
        cost = rate * count * allocation * working_days
        total += cost
    return total

def build_draft(kb, industry, project_type, client_name):
    vendor = kb['vendor']
    case_studies = filter_case_studies(kb.get('case_studies', []), industry)
    team_template = get_team_template(kb.get('team_templates', {}), project_type)
    methodology = kb.get('methodology', {})
    rates = kb.get('pricing', {}).get('daily_rates', {})
    differentiators = get_differentiators(kb.get('differentiators', {}), industry)
    
    total_duration = sum(p.get('duration_weeks', 4) for p in methodology.get('phases', []))
    pricing_estimate = calculate_pricing(rates, team_template, total_duration)
    
    components = [
        {"component": "Professional Services", "amount": int(pricing_estimate)},
        {"component": "Software & Licenses", "amount": int(pricing_estimate * 0.2)},
        {"component": "Travel & Expenses", "amount": int(pricing_estimate * 0.05)}
    ]
    total = sum(c['amount'] for c in components)
    
    milestones = [
        {"percentage": 10, "description": "Project kickoff", "amount": int(total * 0.1)},
        {"percentage": 20, "description": "Design approval", "amount": int(total * 0.2)},
        {"percentage": 30, "description": "Go-live", "amount": int(total * 0.3)},
        {"percentage": 40, "description": "Final acceptance", "amount": int(total * 0.4)}
    ]
    
    draft = {
        "client": {
            "name": client_name,
            "industry": industry,
            "size_employees": 1000,
            "description": f"{client_name} is a {industry} organization seeking digital transformation."
        },
        "vendor": vendor,
        "needs": {
            "challenges": [
                "Legacy system limitations",
                "Scalability constraints", 
                "Compliance requirements"
            ],
            "objectives": [
                "Modernize infrastructure",
                "Improve operational efficiency",
                "Reduce total cost of ownership"
            ]
        },
        "solution": {
            "overview": f"Comprehensive {project_type.replace('_', ' ')} solution leveraging industry best practices and proven methodology.",
            "scope": [
                "Assessment and planning",
                "Architecture design",
                "Implementation and migration",
                "Training and knowledge transfer"
            ],
            "deliverables": [
                "Project documentation",
                "Trained staff",
                "Operational system",
                "Support documentation"
            ]
        },
        "methodology": methodology,
        "timeline": {
            "total_duration_weeks": total_duration,
            "phases": methodology.get('phases', [])
        },
        "pricing": {
            "currency": kb.get('pricing', {}).get('currency', 'USD'),
            "professional_services": int(pricing_estimate),
            "components": components,
            "total": total,
            "payment_milestones": milestones
        },
        "team": team_template.get('roles', []),
        "case_studies": case_studies,
        "terms": {
            "validity_days": 120,
            "warranty_period": "12 months",
            "governing_law": "State of [Your State]",
            "payment_terms": "Net 30 days from invoice date"
        },
        "next_steps": [
            "Schedule discovery workshop",
            "Finalize scope and timeline",
            "Execute master services agreement"
        ]
    }
    return draft

def main():
    parser = argparse.ArgumentParser(description='Query KB and generate draft intake')
    parser.add_argument('--kb', required=True, help='Path to kb.json')
    parser.add_argument('--industry', required=True)
    parser.add_argument('--project-type', required=True)
    parser.add_argument('--client', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    
    kb = load_kb(args.kb)
    draft = build_draft(kb, args.industry, args.project_type, args.client)
    
    with open(args.output, 'w') as f:
        json.dump(draft, f, indent=2)
    
    print(f"✅ Draft intake generated: {args.output}")
    print(f"💰 Estimated value: ${draft['pricing']['total']:,} {draft['pricing']['currency']}")
    print(f"📊 Duration: {draft['timeline']['total_duration_weeks']} weeks")
    print(f"👥 Team: {len(draft['team'])} roles")

if __name__ == '__main__':
    main()
