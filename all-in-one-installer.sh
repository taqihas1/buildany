# Proposal Craft Skill

Generate professional IT consulting proposals from structured intake data.

## Quick Start

```bash
cd ~/.openclaw/skills/proposal-craft
python3 scripts/generator.py \
  --intake references/sample-intake.json \
  --template assets/proposal-template.md \
  --output proposal.md
```

## Workflow

1. **Query KB** (if using proposal-kb) to get draft intake
2. **Customize intake JSON** with client-specific details
3. **Run generator** to produce Markdown document
4. **Convert** to PDF/Word as needed

## Template Variables

- `{{client.name}}` — Client company name
- `{{vendor.company_name}}` — Your company name
- `{{solution.overview}}` — Solution description
- `{{pricing.total}}` — Total investment amount
- `{{#team}}...{{/team}}` — Team member loop
- `{{#case_studies}}...{{/case_studies}}` — Case study loop
